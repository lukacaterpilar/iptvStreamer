enum class Lang(val code: String, val label: String) {
    HR("hr", "Hrvatski"), EN("en", "English"), IT("it", "Italiano"), DE("de", "Deutsch");

    companion object {
        fun fromCode(code: String?) = entries.firstOrNull { it.code == code } ?: HR
    }
}

/** Current UI language. Reading [S] inside a composable recomposes it when the language changes. */
object L10n {
    var lang by mutableStateOf(Lang.HR)
    val strings: Strings get() = when (lang) {
        Lang.HR -> HR
        Lang.EN -> EN
        Lang.IT -> IT
        Lang.DE -> DE
    }
}

val S: Strings get() = L10n.strings

